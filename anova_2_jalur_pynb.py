import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

import statsmodels.api as sm
from statsmodels.formula.api import ols
from statsmodels.stats.anova import anova_lm
from statsmodels.stats.multicomp import pairwise_tukeyhsd
from statsmodels.stats.diagnostic import het_breuschpagan
from statsmodels.stats.stattools import durbin_watson
from statsmodels.stats.outliers_influence import variance_inflation_factor
import scipy.stats as scstats

import warnings
warnings.filterwarnings('ignore')

# Pengaturan visualisasi seaborn
sns.set_theme(style="whitegrid")
plt.rcParams['figure.figsize'] = (10, 5)

# --- 1. UPLOAD DATASET & VISUALISASI AWAL ---

df = pd.read_csv('StudentsPerformance.csv')
df.columns = df.columns.str.replace(' ', '_')

print("=== LANGKAH 1: UPLOAD & CEK DATA ===")
print("Jumlah Baris dan Kolom:", df.shape)

plt.figure(figsize=(10, 4))
plt.subplot(1, 2, 1)
sns.countplot(x='gender', data=df, palette='Set2')
plt.title('Visualisasi 1.1: Distribusi Gender', fontsize=11, fontweight='bold')

plt.subplot(1, 2, 2)
sns.countplot(x='test_preparation_course', data=df, palette='Set3')
plt.title('Visualisasi 1.2: Distribusi Kursus', fontsize=11, fontweight='bold')
plt.tight_layout()
plt.show()


# --- 2. PERUMUSAN HIPOTESIS & FORMULA STATISTIK ---
print("="*65)
print("=== LANGKAH 2: FORMULA & PERUMUSAN HIPOTESIS ANOVA 2 JALUR ===")
print("="*65)
print("Variabel Dependen (Y) : math_score")
print("Variabel Independen (X): gender (Faktor A) & test_preparation_course (Faktor B)\n")

print("FORMULA MATEMATIS OLS / ANOVA 2 JALUR:")
print("Y = μ + α_i + β_j + (αβ)_ij + ε_ij")
print("Dimana:")
print(" - μ        : Rata-rata keseluruhan")
print(" - α_i      : Pengaruh faktor Gender (i = Laki-laki, Perempuan)")
print(" - β_j      : Pengaruh faktor Test Preparation Course (j = None, Completed)")
print(" - (αβ)_ij  : Pengaruh Interaksi antara Gender dan Test Preparation Course")
print(" - ε_ij     : Galat (Residual)\n")

print("PERUMUSAN HIPOTESIS:")
print("1. Pengaruh Faktor A (Gender):")
print("   - H0: Tidak ada perbedaan rata-rata skor matematika antara siswa laki-laki dan perempuan.")
print("   - H1: Terdapat perbedaan rata-rata skor matematika antara siswa laki-laki dan perempuan.\n")

print("2. Pengaruh Faktor B (Test Preparation Course):")
print("   - H0: Tidak ada perbedaan rata-rata skor matematika antara yang mengikuti kursus dan tidak.")
print("   - H1: Terdapat perbedaan rata-rata skor matematika antara yang mengikuti kursus dan tidak.\n")

print("3. Pengaruh Interaksi (Gender * Test Preparation Course):")
print("   - H0: Tidak ada interaksi signifikan antara gender dan kursus persiapan terhadap skor matematika.")
print("   - H1: Terdapat interaksi signifikan antara gender dan kursus persiapan terhadap skor matematika.")
print("="*65)

plt.figure(figsize=(12, 4))
plt.subplot(1, 2, 1)
sns.histplot(df['math_score'], kde=True, color='royalblue', bins=20)
plt.title('Visualisasi 2.1: Histogram Skor', fontsize=11, fontweight='bold')

plt.subplot(1, 2, 2)
sns.boxplot(y=df['math_score'], color='lightblue')
plt.title('Visualisasi 2.2: Boxplot Skor (Outlier Check)', fontsize=11, fontweight='bold')
plt.tight_layout()
plt.show()


# --- 3. PREPROCESSING DATA ---
print("\n=== LANGKAH 3: PREPROCESSING DATA ===")
print("Cek Missing Values:\n", df.isnull().sum())

df['gender'] = df['gender'].astype('category')
df['test_preparation_course'] = df['test_preparation_course'].astype('category')

plt.figure(figsize=(8, 3))
sns.heatmap(df.isnull(), cbar=False, cmap='viridis', yticklabels=False)
plt.title('Visualisasi 3: Heatmap Missing Values (Bersih)', fontsize=11, fontweight='bold')
plt.show()


# --- 4. 4 UJI ASUMSI KLASIK ---
print("\n=== LANGKAH 4: 4 UJI ASUMSI KLASIK & VISUALISASINYA ===")
model_formula = 'math_score ~ C(gender) + C(test_preparation_course) + C(gender):C(test_preparation_course)'
model = ols(model_formula, data=df).fit()
residuals = model.resid
fitted_vals = model.fittedvalues

# 4.1 Normalitas
res_sample = residuals.sample(n=min(500, len(residuals)), random_state=42)
stat_sw, p_sw = scstats.shapiro(res_sample)
print(f"1. Uji Normalitas (Shapiro-Wilk) p-value: {p_sw:.4e}")

plt.figure(figsize=(7, 4))
scstats.probplot(residuals, dist="norm", plot=plt)
plt.title("Visualisasi 4.1: Q-Q Plot Residual (Uji Normalitas)", fontsize=11, fontweight='bold')
plt.show()

# 4.2 Homoskedastisitas
try:
    bp_test = het_breuschpagan(residuals, model.model.exog)
    print(f"2. Uji Homoskedastisitas (Breusch-Pagan) p-value: {bp_test[3]:.4e}")
except:
    pass

plt.figure(figsize=(7, 4))
sns.scatterplot(x=fitted_vals, y=residuals, alpha=0.6, color='purple')
plt.axhline(0, color='red', linestyle='--')
plt.title("Visualisasi 4.2: Residual vs Fitted Plot (Uji Homoskedastisitas)", fontsize=11, fontweight='bold')
plt.xlabel("Fitted Values")
plt.ylabel("Residuals")
plt.show()

# 4.3 Multikolinearitas (VIF)
exog_matrix = sm.add_constant(pd.DataFrame(model.model.exog))
vif_data = pd.DataFrame()
vif_data["feature"] = exog_matrix.columns
vif_data["VIF"] = [variance_inflation_factor(exog_matrix.values, i) for i in range(exog_matrix.shape[1])]
vif_data = vif_data[vif_data['feature'] != 'const']
print("3. Uji Multikolinearitas (VIF):\n", vif_data)

plt.figure(figsize=(7, 4))
sns.barplot(x='feature', y='VIF', data=vif_data, palette='coolwarm')
plt.axhline(10, color='red', linestyle='--', label='Batas VIF (10)')
plt.title("Visualisasi 4.3: Barplot Nilai VIF (Uji Multikolinearitas)", fontsize=11, fontweight='bold')
plt.xticks(rotation=15)
plt.legend()
plt.show()

# 4.4 Autokorelasi (Durbin-Watson)
dw_val = durbin_watson(residuals)
print(f"4. Uji Autokorelasi (Durbin-Watson) Nilai DW: {dw_val:.4f}")

plt.figure(figsize=(9, 3.5))
plt.plot(residuals.values[:100], marker='o', linestyle='-', color='teal', alpha=0.7)
plt.axhline(0, color='red', linestyle='--')
plt.title("Visualisasi 4.4: Plot Residual Urutan Data (Uji Autokorelasi)", fontsize=11, fontweight='bold')
plt.xlabel("Urutan Observasi")
plt.ylabel("Residual")
plt.show()


# --- 5. MODELING ANOVA 2 JALUR ---
print("\n=== LANGKAH 5: MODELING ANOVA 2 JALUR ===")
anova_table = anova_lm(model, typ=2)
display(anova_table)

plt.figure(figsize=(8, 4.5))
sns.barplot(x='gender', y='math_score', hue='test_preparation_course', data=df, palette='Set2', errorbar=None)
plt.title('Visualisasi 5: Interaction Plot Skor Matematika', fontsize=11, fontweight='bold')
plt.xlabel('Gender Siswa')
plt.ylabel('Rata-rata Skor Matematika')
plt.legend(title='Test Prep Course')
plt.show()


# --- 6. EVALUASI DAN POST-HOC TEST (TUKEY HSD) ---
print("\n=== LANGKAH 6: EVALUASI & POST-HOC TEST (TUKEY HSD) ===")
df['interaction_group'] = df['gender'].astype(str) + " (" + df['test_preparation_course'].astype(str) + ")"
tukey = pairwise_tukeyhsd(endog=df['math_score'], groups=df['interaction_group'], alpha=0.05)
print(tukey)

tukey_summary = tukey.summary().data
tukey_df = pd.DataFrame(data=tukey_summary[1:], columns=tukey_summary[0])
tukey_df['comparison'] = tukey_df['group1'].astype(str) + " vs " + tukey_df['group2'].astype(str)

tukey_df['meandiff'] = pd.to_numeric(tukey_df['meandiff'])
tukey_df['lower'] = pd.to_numeric(tukey_df['lower'])
tukey_df['upper'] = pd.to_numeric(tukey_df['upper'])

xerr_low = tukey_df['meandiff'] - tukey_df['lower']
xerr_high = tukey_df['upper'] - tukey_df['meandiff']
colors = ['forestgreen' if (r == True or r == 'True') else 'indianred' for r in tukey_df['reject']]

plt.figure(figsize=(10, 5))
y_pos = np.arange(len(tukey_df))

plt.errorbar(tukey_df['meandiff'], y_pos, xerr=[xerr_low, xerr_high], fmt='o', color='black', capsize=4, elinewidth=1.5)
plt.barh(y_pos, tukey_df['meandiff'], color=colors, alpha=0.6, height=0.4)

plt.axvline(0, color='grey', linestyle='--', linewidth=1.2)
plt.yticks(y_pos, tukey_df['comparison'], fontsize=9)
plt.xlabel('Mean Difference & Confidence Interval', fontsize=10, fontweight='bold')
plt.title('Visualisasi 6: Diagram Batang Tukey HSD Post-Hoc Test', fontsize=11, fontweight='bold')
plt.grid(axis='x', linestyle='--', alpha=0.7)
plt.tight_layout()
plt.show()